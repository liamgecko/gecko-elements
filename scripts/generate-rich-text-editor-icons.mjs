// Run after build:package when updating the Rich text editor's Hugeicons mapping.
// TinyMCE owns its DOM, so render Gecko glyphs to CSS masks without adding React roots.
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { writeFile } from "node:fs/promises";
import { HugeiconsIcon } from "../packages/ui/dist/lib/icon.js";

const icons = {
  code: "CodeIcon",
  removeformat: "TextClearIcon",
  undo: "Undo02Icon",
  redo: "Redo02Icon",
  bold: "TextBoldIcon",
  italic: "TextItalicIcon",
  underline: "TextUnderlineIcon",
  strikethrough: "TextStrikethroughIcon",
  forecolor: "TextColorIcon",
  bullist: "LeftToRightListBulletIcon",
  numlist: "LeftToRightListNumberIcon",
  indent: "TextIndentMoreIcon",
  outdent: "TextIndentLessIcon",
  alignleft: "TextAlignLeftIcon",
  aligncenter: "TextAlignCenterIcon",
  alignright: "TextAlignRightIcon",
  alignjustify: "TextAlignJustifyCenterIcon",
  image: "Image02Icon",
  link: "Link01Icon",
  table: "GridTableIcon",
  hr: "MinusSignIcon",
  charmap: "OmegaIcon",
  pastetext: "ClipboardPasteIcon",
};
let css = "";
for (const [name, glyph] of Object.entries(icons)) {
  const { default: icon } = await import(`@hugeicons/core-free-icons/${glyph}`);
  const svg = renderToStaticMarkup(
    createElement(HugeiconsIcon, {
      icon,
      size: 18,
      strokeWidth: glyph === "OmegaIcon" ? 0 : 2,
    }),
  );
  const uri = `data:image/svg+xml,${encodeURIComponent(svg)}`;
  css += `.mce-toolbar .mce-i-${name}::before { content:""; display:block; width:18px; height:18px; background:currentColor; mask:url("${uri}") center/contain no-repeat; }\n`;
}
await writeFile(
  new URL("../packages/ui/src/lib/rich-text-editor-icons.ts", import.meta.url),
  "// Generated by scripts/generate-rich-text-editor-icons.mjs through the Gecko icon renderer.\nexport const editorToolbarIconsCss = " +
    JSON.stringify(css) +
    ";\n",
);
